package Exercicios4;

public class Exercicio6 {
    public static void main(String[] args) {
        int num1 = 15;
        int num2 = 20;

        System.out.println("--- Exercício 6 ---");
        System.out.println("Comparando " + num1 + " e " + num2 + ":");
        System.out.println(num1 + " > " + num2 + " : " + (num1 > num2));
        System.out.println(num1 + " < " + num2 + " : " + (num1 < num2));
        System.out.println(num1 + " >= " + num2 + " : " + (num1 >= num2));
        System.out.println(num1 + " <= " + num2 + " : " + (num1 <= num2));
        System.out.println(num1 + " == " + num2 + " : " + (num1 == num2));
        System.out.println(num1 + " != " + num2 + " : " + (num1 != num2));
    }
}
